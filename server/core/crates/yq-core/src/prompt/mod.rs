//! prompt 组装 —— KV-cache 前缀（一等设计约束）
//!
//! 上下文组装顺序（SPEC 第四节，严格固定）：
//!
//! ```text
//! [固定区] 系统提示 + 工具定义 + persona + 静态指令
//! [动态区] 本轮记忆注入（追加） + 历史对话 + 当前用户消息
//! ```
//!
//! 硬性规则：
//!   1. 固定区必须字节级固定 —— 时间戳 / UUID / 随机数一律不得出现
//!   2. 记忆注入只能**追加**，不得前置、不得插入固定区
//!   3. 工具定义顺序确定，不因运行时状态重排
//!   4. 工具结果、心跳消息、子代理摘要只能出现在动态区

pub mod context;
pub mod prefix;

pub use context::{BuiltContext, ContextBuilder};
pub use prefix::StaticPrefix;

